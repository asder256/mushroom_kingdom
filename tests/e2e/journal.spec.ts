test('local spot and visits survive refresh, backup restores, delete confirms', async ({ page }) => {
  await page.goto('#local');
  await page.getByRole('button', { name: 'Enter coordinates' }).click();
  await page.getByLabel('Spot name', { exact: true }).fill('Test fictional glade');
  await page.getByLabel('Latitude', { exact: true }).fill('59.44');
  await page.getByLabel('Longitude', { exact: true }).fill('15.21');
  await page.getByRole('button', { name: '+ Add species', exact: true }).click();
  await page.getByLabel('Common name 1', { exact: true }).fill('Fictional mushroom');
  await page.getByRole('button', { name: '+ Add visit' }).click();
  await page.getByLabel('Visit date', { exact: true }).fill('2026-10-10');
  await page.getByLabel('Private visit notes').fill('Never publish this');
  await page.getByLabel('Include this spot in public export').check();
  await page.getByRole('button', { name: 'Save spot locally' }).click();
  await expect(page.getByRole('heading', { name: 'Test fictional glade' })).toBeVisible();
  await page.reload();
  await expect(page.locator('.spot-card')).toContainText('Test fictional glade');
  await page.getByRole('link', { name: 'Backup & publishing', exact: true }).click();
  await page.getByRole('button', { name: /Back up & restore/ }).click();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: /Download private backup/ }).click();
  const file = await downloaded; const path = await file.path();
  await page.getByRole('link', { name: 'My local journal', exact: true }).click();
  await page.getByRole('button', { name: 'Open notes for Test fictional glade' }).click();
  page.once('dialog', d => d.accept());
  await page.getByRole('button', { name: 'Delete spot', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Every journal starts somewhere.' })).toBeVisible();
  await page.getByRole('link', { name: 'Backup & publishing', exact: true }).click();
  await page.getByRole('button', { name: /Back up & restore/ }).click();
  await page.getByText('Restore from a private backup', { exact: true }).click();
  await page.getByLabel('Restore a journal backup (.json)').setInputFiles(path!);
  await expect(page.getByRole('heading', { name: 'Restore preview' })).toBeVisible();
  page.once('dialog', d => d.accept());
  await page.getByRole('button', { name: 'Back up current journal & confirm restore' }).click();
  await expect(page.getByRole('status')).toContainText('Backup restored');
  await page.getByRole('button', { name: /Prepare publication/ }).click();
  await page.getByRole('button', { name: 'Review public export' }).click();
  await page.getByText('Inspect complete public JSON').click();
  await expect(page.locator('pre')).toContainText('Test fictional glade');
  await expect(page.locator('pre')).not.toContainText('Never publish this');
});
